export function getQuestions(language) {
  const translations = QUESTION_TEXTS[language]
  const optionTranslations = OPTION_TEXTS[language]
  if (!translations) return QUESTIONS

  return QUESTIONS.map((question, index) => ({
    ...question,
    text: translations[index] ?? question.text,
    options: (optionTranslations?.[index] ?? question.options).map((option, optionIndex) => ({
      ...option,
      text: optionTranslations?.[index]?.[optionIndex] ?? option.text,
    })),
  }))
}
